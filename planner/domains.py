# planner/domains.py —— L2 的「域」：一次规划只带一个域的技能表和专家册。
#
# 为什么要有这一层：L1 是人格层（小傻瓜，只管想做什么），L2 是专家（懂 MC，负责把一句话变成能执行的步骤）。
# 技能多了之后，把所有技能和所有知识都塞进一个 system prompt，模型会开始混参数、漏字段——这是注意力压力，
# 不是能力问题。所以按域切开：路由器（纯关键词，不过模型、零成本）先判这一句属于哪一域，
# 只把该域的技能行 + 专家册交给 L2。
#
# 专家册只写「机制」，不写会过期的坐标与数值（矿石分布标了版本，版本大改要复核）。
# 更重要的：只能写我们真有的能力——册子里出现 skills/ 里没有的技能，L2 会照写，schema 会拒收。
from dataclasses import dataclass, field


@dataclass(frozen=True)
class Domain:
    name: str
    # 这一域允许的技能名，必须是 schema.ALL_SKILLS 的子集
    skills: tuple[str, ...]
    # 路由关键词（子串命中即可，中文直接写）
    keywords: tuple[str, ...]
    # 专家册：给 L2 的领域知识。空串＝没有额外知识。
    brief: str = ""
    # 这一域额外的规则行（通用规则之外的）
    rules: tuple[str, ...] = field(default_factory=tuple)


