DOMAINS: dict[str, Domain] = {
    d.name: d for d in (_GATHER, _CRAFT, _INTERACT, _TRAVEL, _COMBAT)
}

# 兜底域：一句都没命中就用它，技能全开、没有专家册，行为和加域之前完全一致。
GENERAL = Domain(
    name="general",
    skills=(
        "mine", "goto", "follow", "craft", "deposit", "attack",
        "eat", "equip", "place", "roam", "drop", "open",
        "smelt", "sleep", "use",
    ),
    keywords=(),
)

# 一句话里出现多个域时，按这个顺序取第一个命中的：
# 具体动作（合成、存取、战斗）比泛化的"去/来"更能说明意图。
_PRIORITY = ("craft", "combat", "interact", "gather", "travel")


def route(text: str) -> Domain:
    """一句话 → 域。纯字符串匹配，不过模型、不花钱、可预期。

    宁可选兜底也不要选错：命中不了任何关键词就走 general（全技能、无专家册），
    这样最坏情况和加域之前一样，不会因为路由把能做的事变得做不了。
    """
    body = str(text or "")
    if not body:
        return GENERAL
    for name in _PRIORITY:
        domain = DOMAINS[name]
        if any(word in body for word in domain.keywords):
            return domain
    return GENERAL


def by_name(name: str) -> Domain:
    return DOMAINS.get(str(name or ""), GENERAL)
